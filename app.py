"""Streamlit interface for the Group 3 early dropout-risk prototype.

Run: streamlit run app.py
Set DROPOUT_ARTIFACTS to point at the real model artifact directory when available.
"""
from pathlib import Path
import os
import tempfile

import pandas as pd
import streamlit as st

from predictor import ArtifactError, DropoutPredictor, InputError, find_artifact_dir

st.set_page_config(page_title="Student Dropout Risk", page_icon="🎓", layout="wide")
st.title("Student Academic Performance & Dropout Risk")
st.caption("Group 3 · FUSE-AI-201 · Application implementation")

@st.cache_resource
def load_predictor(artifact_path: str):
    return DropoutPredictor(artifact_path)

artifact_dir = find_artifact_dir()
try:
    predictor = load_predictor(str(artifact_dir))
except ArtifactError as exc:
    st.error(f"Could not load the prediction model. {exc}")
    st.info("Place the model pipeline and metadata in model_artifacts/, or run build_demo_artifacts.py for a synthetic demonstration.")
    st.stop()

if predictor.is_synthetic:
    st.warning(
        "DEMO MODEL ONLY: this model was trained on synthetic/randomly generated data. "
        "Its scores are not meaningful estimates of real students' dropout risk. "
        "Use it only to demonstrate application behavior."
    )
for warning in predictor.load_warnings:
    st.warning(warning)

with st.sidebar:
    st.header("About this prototype")
    st.write("Prediction point: end of semester one.")
    st.write(f"Flag threshold: **{predictor.threshold:.3f}**")
    st.write("Only the saved model's approved first-semester input fields are used.")
    st.caption("Decision support only. Do not use scores to penalize students or make automated decisions.")

tab_single, tab_batch, tab_info = st.tabs(["Single student", "Batch CSV", "How to use"])

def show_results(scored):
    results = scored.results.copy()
    if predictor.can_explain:
        results["main_risk_factors"] = predictor.main_risk_factors(scored.features)
    for note in scored.notes:
        st.info(note)
    st.dataframe(results, use_container_width=True, hide_index=True)
    csv = results.to_csv(index=False).encode("utf-8")
    st.download_button("Download predictions as CSV", data=csv,
                       file_name="student_dropout_predictions.csv", mime="text/csv")
    if len(results) == 1:
        row = results.iloc[0]
        score = float(row["risk_score"])
        c1, c2, c3 = st.columns(3)
        c1.metric("Estimated dropout risk score", f"{score:.1%}")
        c2.metric("Predicted class", str(row["predicted_class"]))
        c3.metric("Flag for advisor review", "Yes" if bool(row["flagged"]) else "No")
        if predictor.is_synthetic:
            st.caption("This displayed score is generated by a synthetic demo model and must not be interpreted as a real risk estimate.")
        if predictor.can_explain:
            x = scored.features.iloc[0]
            contributions = predictor.contributions(scored.features).iloc[0]
            up, down = predictor.top_factors(contributions, x)
            left, right = st.columns(2)
            with left:
                st.subheader("Factors associated with higher score")
                st.dataframe(up, use_container_width=True, hide_index=True)
            with right:
                st.subheader("Factors associated with lower score")
                st.dataframe(down, use_container_width=True, hide_index=True)

with tab_single:
    st.write("Enter the student's first-semester information. The field labels and valid values come from the loaded model.")
    with st.form("student_form"):
        values = {}
        cols = st.columns(3)
        # Use a sample record as sensible defaults when available.
        sample_path = Path(__file__).resolve().parent / "sample_students.csv"
        sample = pd.read_csv(sample_path).iloc[0] if sample_path.exists() else pd.Series(dtype=object)
        for i, field in enumerate(predictor.features):
            with cols[i % 3]:
                if field in predictor.binary:
                    default = int(sample[field]) if field in sample else 0
                    values[field] = int(st.selectbox(field, [0, 1], index=default,
                                                       format_func=lambda x: "Yes / 1" if x == 1 else "No / 0",
                                                       key=f"single_{field}"))
                elif field in predictor.categorical:
                    options = predictor.categories[field]
                    default = sample[field] if field in sample and sample[field] in options else options[0]
                    values[field] = st.selectbox(field, options, index=options.index(default),
                                                 key=f"single_{field}")
                else:
                    default = float(sample[field]) if field in sample else float(predictor.num_mean[field])
                    values[field] = st.number_input(field, value=default, key=f"single_{field}")
        student_id = st.text_input("Student ID (optional)", value="DEMO-NEW")
        submitted = st.form_submit_button("Estimate dropout risk", type="primary")
    if submitted:
        record = pd.DataFrame([values])
        record.insert(0, "Student ID", student_id.strip() or "Student 1")
        try:
            scored = predictor.predict(record)
            show_results(scored)
        except InputError as exc:
            st.error(f"Please check the inputs: {exc}")

with tab_batch:
    st.write("Upload a CSV containing all required first-semester fields. Extra identifier columns are retained; second-semester fields and `Target` are ignored.")
    uploaded = st.file_uploader("Upload student records (.csv)", type=["csv"])
    if uploaded is not None:
        try:
            batch = pd.read_csv(uploaded, sep=None, engine="python")
            st.write(f"Loaded {len(batch)} student records.")
            st.dataframe(batch.head(10), use_container_width=True, hide_index=True)
            if st.button("Score uploaded students", type="primary"):
                scored = predictor.predict(batch)
                show_results(scored)
        except (InputError, UnicodeDecodeError, pd.errors.ParserError) as exc:
            st.error(f"Could not process this file: {exc}")

with tab_info:
    st.subheader("Expected CSV format")
    st.write("Include the 30 input fields expected by the model. An optional `Student ID` column can identify rows.")
    st.code("python predictor.py --csv sample_students.csv --explain", language="bash")
    st.write("The command above runs batch scoring from the command line.")
    st.write("Risk scores are model outputs, not causes or certainties. A trained model should be evaluated on held-out data before any real-world use.")
